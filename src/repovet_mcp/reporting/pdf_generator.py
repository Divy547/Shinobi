class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas for adding running footers with dynamic 'Page X of Y' numbers."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._saved_page_states: list[dict[str, Any]] = []

    def showPage(self) -> None:  # noqa: N802
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int) -> None:
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        # Running Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(36, 756, "RepoVet MCP — Autonomous Open-Source Vetting Audit Report")
            self.drawRightString(576, 756, "CONFIDENTIAL & GROUNDED DUE DILIGENCE")
            self.setStrokeColor(colors.HexColor("#cbd5e1"))
            self.setLineWidth(0.5)
            self.line(36, 750, 576, 750)

        # Running Footer (all pages)
        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.5)
        self.line(36, 42, 576, 42)

        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawString(36, 30, "Generated by RepoVet MCP • https://modelcontextprotocol.io")
        self.drawRightString(576, 30, page_str)
        self.restoreState()


class PDFReportGenerator:
    """Generates professional, publication-quality PDF audit reports using ReportLab."""

    def __init__(self, settings: Settings | None = None) -> None:
        self.settings = settings or get_settings()
        self.output_dir = self.settings.reports_dir / "generated"
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def _setup_styles(self) -> dict[str, ParagraphStyle]:
        """Initialize custom typography hierarchy."""
        base_styles = getSampleStyleSheet()
        custom = {}

        custom["DocTitle"] = ParagraphStyle(
            "DocTitle",
            parent=base_styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#0f172a"),
            spaceAfter=4,
        )
        custom["DocSubtitle"] = ParagraphStyle(
            "DocSubtitle",
            parent=base_styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=11,
            leading=14,
            textColor=colors.HexColor("#2563eb"),
            spaceAfter=12,
        )
        custom["SectionHeading"] = ParagraphStyle(
            "SectionHeading",
            parent=base_styles["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=13,
            leading=16,
            textColor=colors.HexColor("#1e293b"),
            spaceBefore=14,
            spaceAfter=8,
            keepWithNext=True,
        )
        custom["Body"] = ParagraphStyle(
            "Body",
            parent=base_styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=13,
            textColor=colors.HexColor("#334155"),
            spaceAfter=6,
        )
        custom["BodyBold"] = ParagraphStyle(
            "BodyBold",
            parent=custom["Body"],
            fontName="Helvetica-Bold",
        )
        custom["TableCell"] = ParagraphStyle(
            "TableCell",
            parent=base_styles["Normal"],
            fontName="Helvetica",
            fontSize=8,
            leading=11,
            textColor=colors.HexColor("#1e293b"),
        )
        custom["TableCellBold"] = ParagraphStyle(
            "TableCellBold",
            parent=custom["TableCell"],
            fontName="Helvetica-Bold",
        )
        custom["DecisionBadge"] = ParagraphStyle(
            "DecisionBadge",
            fontName="Helvetica-Bold",
            fontSize=24,
            leading=28,
            alignment=1,  # Center
            textColor=colors.white,
        )
        custom["DecisionSub"] = ParagraphStyle(
            "DecisionSub",
            fontName="Helvetica-Bold",
            fontSize=11,
            leading=14,
            alignment=1,  # Center
            textColor=colors.HexColor("#f8fafc"),
        )

        return custom

