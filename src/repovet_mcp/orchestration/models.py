"""Pydantic data models and schemas for AI orchestration and MCP integration."""

from typing import Any

from pydantic import BaseModel, Field

from repovet_mcp.models.audit import AuditDecision, AuditReport, HardGateResult, Scorecard


class ToolCallRecord(BaseModel):
    """Execution trace of an individual tool call executed by an MCP client."""

    call_id: str = Field(description="Unique identifier for this tool call execution")
    tool_name: str = Field(description="Name of the MCP tool invoked")
    arguments: dict[str, Any] = Field(
        default_factory=dict, description="Sanitized arguments passed to the tool"
    )
    target_client: str = Field(
        description="Target MCP client responsible for execution ('shinobi' or 'github')"
    )
    result: Any = Field(default=None, description="Output payload returned by the tool execution")
    is_error: bool = Field(
        default=False, description="Whether the tool execution failed or threw an error"
    )
    duration_seconds: float = Field(default=0.0, description="Execution duration in seconds")
    step_index: int = Field(default=0, description="Sequential loop step index")


class OrchestrationRequest(BaseModel):
    """User request for autonomous repository vetting via Gemini orchestration."""

    prompt: str = Field(description="Natural language instruction or repository vetting request")
    target_repository: str | None = Field(
        default=None, description="Optional repository identifier (owner/repo or URL)"
    )
    audit_id: str | None = Field(
        default=None, description="Optional existing or custom audit identifier"
    )
    max_steps: int | None = Field(
        default=None, description="Optional override for maximum tool-calling loop iterations"
    )


class OrchestrationResult(BaseModel):
    """Structured outcome of an orchestration session with strict scoring and evidence boundaries."""

    prompt: str = Field(description="Original user prompt")
    final_summary: str = Field(
        description="Gemini-generated natural language summary and synthesis"
    )
    audit_id: str | None = Field(
        default=None, description="Audit identifier associated with this vetting session"
    )
    # Deterministic Shinobi results (immutable by Gemini)
    audit_report: AuditReport | None = Field(
        default=None,
        description="Deterministic AuditReport from Shinobi (None if not generated)",
    )
    scorecard: Scorecard | None = Field(
        default=None,
        description="Deterministic Shinobi 10-criterion scorecard (immutable by LLM)",
    )
    decision: AuditDecision | None = Field(
        default=None,
        description="Deterministic Shinobi audit decision (APPROVE, CONDITIONAL, REJECT, NEEDS MANUAL REVIEW)",
    )
    hard_gates: list[HardGateResult] = Field(
        default_factory=list,
        description="Evaluated mandatory eligibility hard gates from Shinobi",
    )
    # Execution traces and boundary separation
    tool_calls: list[ToolCallRecord] = Field(
        default_factory=list, description="Chronological record of all tool calls made"
    )
    github_mcp_observations: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Contextual observations from the official GitHub MCP server (unverified as audit evidence)",
    )
    shinobi_verified_evidence_count: int = Field(
        default=0,
        description="Count of grounded, confirmed evidence items generated by Shinobi engine",
    )
    # Session metadata
    iterations_used: int = Field(default=0, description="Number of model turns executed")
    total_duration_seconds: float = Field(
        default=0.0, description="Total orchestration session elapsed time in seconds"
    )
    is_completed: bool = Field(
        default=True,
        description="Whether the orchestration concluded normally without hitting limits",
    )
    error: str | None = Field(
        default=None, description="Error message if orchestration failed or was aborted"
    )
